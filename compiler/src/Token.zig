const std = @import("std");

const Self = @This();

pub const TokenType = enum {
    left_paren,
    right_paren,
    left_brace,
    right_brace,
    left_bracket,
    right_bracket,
    colon,
    comma,
    dot,
    dot_dot,
    pipe,
    minus,
    plus,
    semicolon,
    slash,
    star,
    percent,
    bang,
    bang_eql,
    eql,
    eql_eql,
    greater,
    greater_eql,
    less,
    less_eql,
    identifier,
    score_identifier,
    data_identifier,
    // The NBT path after `@s.$`, for example `Inventory[0].count`.
    entity_data,
    command,
    selector,
    execute_subcommands,
    string,
    number,
    @"and",
    as,
    @"break",
    @"continue",
    @"else",
    execute,
    false,
    mcfun,
    @"for",
    @"if",
    import,
    null,
    @"or",
    @"return",
    true,
    @"var",
    @"while",
    eof,
    illegal,
    // A string, `(` or `[` that is not closed. The literal is the missing character.
    unclosed,
};

pub const Keywords = std.StaticStringMap(TokenType).initComptime(.{
    .{ "and", .@"and" },
    .{ "as", .as },
    .{ "break", .@"break" },
    .{ "continue", .@"continue" },
    .{ "else", .@"else" },
    .{ "execute", .execute },
    .{ "false", .false },
    .{ "for", .@"for" },
    .{ "mcfun", .mcfun },
    .{ "if", .@"if" },
    .{ "import", .import },
    .{ "null", .null },
    .{ "or", .@"or" },
    .{ "return", .@"return" },
    .{ "var", .@"var" },
    .{ "true", .true },
    .{ "while", .@"while" },
});

type: TokenType,
literal: []const u8,
line: usize,
column: usize,

pub fn init(@"type": TokenType, literal: []const u8, line: usize, column: usize) Self {
    return .{
        .type = @"type",
        .literal = literal,
        .line = line,
        .column = column,
    };
}
